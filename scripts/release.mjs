// Release helper for maintainers and for .github/workflows/release.yml. See RELEASING.md.
//   prepare <version>  set package.json to <version>, regenerate CHANGELOG.md and UPGRADING.md
//   check <tag>        fail unless HEAD can be published as <tag>
//   notes <tag>        print the GitHub release notes of <tag>
import { execFileSync, spawnSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { compareVersions, findRelease, parseVersion } from '#lib/server/releases.js';
import { loadReleases, renderUpgradeActions, requiresAction } from './release-data.mjs';

process.chdir(fileURLToPath(new URL('..', import.meta.url)));

const GENERATED_NOTICE =
    '<!-- Generated by scripts/release.mjs from releases.json and the git history: do not edit. -->';

/** @typedef {import('#lib/server/releases.js').Release} Release */

const git = (/** @type {string[]} */ ...args) => execFileSync('git', args, { encoding: 'utf8' });

/** @param {string} tag */
function parseTag(tag) {
    if (!tag?.startsWith('v'))
        throw new Error(`Invalid tag "${tag}": expected vX.Y.Z or vX.Y.Z-rc.N.`);
    return parseVersion(tag.slice(1));
}

/**
 * The releases published up to `version`, newest first.
 * @param {string} version
 */
function releasesUpTo(version) {
    const releases = loadReleases();
    const base = findRelease(releases, version).version;
    return releases.filter((release) => compareVersions(release.version, base) <= 0);
}

/**
 * Commit range of the newest release (releases[0], up to HEAD) or of an older one (up to its tag),
 * or null for the oldest release, which has no previous version to compare with.
 * @param {Release[]} releases
 * @param {number} index
 */
function commitRange(releases, index) {
    const previous = releases[index + 1];
    if (!previous) return null;
    if (
        spawnSync('git', ['rev-parse', '--verify', '--quiet', `refs/tags/v${previous.version}`])
            .status !== 0
    ) {
        throw new Error(
            `Tag v${previous.version} not found: fetch the tags with "git fetch --tags".`
        );
    }
    return `v${previous.version}..${index === 0 ? 'HEAD' : `v${releases[index].version}`}`;
}

/**
 * @param {Release[]} releases
 * @param {number} index
 */
function renderNotes(releases, index) {
    const release = releases[index];
    const parts = [release.summary, '### Upgrade actions', renderUpgradeActions(release)];
    const range = commitRange(releases, index);
    if (range) {
        const changes = execFileSync(
            'node_modules/.bin/git-cliff',
            ['--config', 'cliff.toml', '--strip', 'all', range],
            {
                encoding: 'utf8',
                // Hides git-cliff's log line; on failure, its stderr is part of the thrown error.
                stdio: 'pipe'
            }
        );
        parts.push('### Changes', changes.trim() || 'None.');
    }
    return parts.join('\n\n');
}

/**
 * The newest section is titled with `version`, which may be a release candidate.
 * @param {string} version
 */
function renderChangelog(version) {
    const releases = releasesUpTo(version);
    const sections = releases.map(
        (release, i) => `## ${i === 0 ? version : release.version}\n\n${renderNotes(releases, i)}`
    );
    return (
        [
            '# Changelog',
            GENERATED_NOTICE,
            'Upgrade actions are also collected in [UPGRADING.md](UPGRADING.md).',
            ...sections
        ].join('\n\n') + '\n'
    );
}

/** @param {string} version */
function renderUpgrading(version) {
    const sections = releasesUpTo(version)
        .filter(requiresAction)
        .map((release) => `## ${release.version}\n\n${renderUpgradeActions(release)}`);
    return (
        [
            '# Upgrading',
            GENERATED_NOTICE,
            'Before installing a new version, apply the actions of every version after the one you run, up to the one you install, oldest first. ' +
                'A **mandatory stop** must be installed and started once before you upgrade past it. Versions not listed here need no manual action.',
            'A release candidate counts as its final version: it needs the same actions, so upgrading from X.Y.Z-rc.N to X.Y.Z needs none.',
            'From a copy of the repository, `node scripts/upgrade-path.mjs <from> <to>` lists the actions and stops of your upgrade.',
            ...sections
        ].join('\n\n') + '\n'
    );
}

const generatedFiles = {
    'CHANGELOG.md': renderChangelog,
    'UPGRADING.md': renderUpgrading
};

/** @param {string} version */
function prepare(version) {
    // Render everything before writing anything, so an error leaves the files untouched.
    const contents = Object.entries(generatedFiles).map(([file, render]) => [
        file,
        render(version)
    ]);
    const packageJson = readFileSync('package.json', 'utf8');
    contents.push([
        'package.json',
        packageJson.replace(/"version": "[^"]*"/, `"version": "${version}"`)
    ]);
    for (const [file, content] of contents) writeFileSync(file, content);
    console.log(
        `Prepared ${version}: review the diff, then commit it as "chore(release): ${version}".`
    );
}

/**
 * Commits marked breaking by Conventional Commits: "type!:" / "type(scope)!:" or a BREAKING CHANGE footer.
 * @param {string} range
 */
function breakingCommits(range) {
    return git('log', '--format=%x00%h %B', range)
        .split('\0')
        .filter(
            (message) =>
                /^\S+ \w+(\([^)]*\))?!:/.test(message) || /^BREAKING[ -]CHANGE:/m.test(message)
        )
        .map((message) => message.split('\n')[0]);
}

/** @param {string} tag */
function check(tag) {
    const version = parseTag(tag);
    const errors = [];

    const packageVersion = JSON.parse(readFileSync('package.json', 'utf8')).version;
    if (packageVersion !== version.text)
        errors.push(`package.json has version ${packageVersion}, not ${version.text}.`);

    // Release candidates are cut from develop, final versions from main.
    const branch = version.isPrerelease ? 'develop' : 'main';
    if (
        spawnSync('git', ['merge-base', '--is-ancestor', 'HEAD', `origin/${branch}`]).status !== 0
    ) {
        errors.push(`${tag} must be on ${branch}, but HEAD is not in origin/${branch}.`);
    }

    const releases = releasesUpTo(version.text);
    const range = commitRange(releases, 0);
    // Checked per version: once it has an action, further breaking commits pass, so whoever adds one updates the actions.
    const breaking = range ? breakingCommits(range) : [];
    if (breaking.length && releases[0].actions.length === 0) {
        errors.push(
            `Breaking commits but no upgrade action for ${releases[0].version} in releases.json:\n  ${breaking.join('\n  ')}`
        );
    }

    for (const [file, render] of Object.entries(generatedFiles)) {
        if (!existsSync(file) || readFileSync(file, 'utf8') !== render(version.text)) {
            errors.push(
                `${file} is out of date: run "node scripts/release.mjs prepare ${version.text}" and commit the result.`
            );
        }
    }

    if (errors.length) throw new Error(`Cannot release ${tag}:\n- ${errors.join('\n- ')}`);
    console.log(`${tag} can be released.`);
}

/** @param {string} tag */
function notes(tag) {
    const releases = releasesUpTo(parseTag(tag).text);
    console.log(renderNotes(releases, 0));
}

/** @type {Record<string, (argument: string) => void>} */
const commands = { prepare, check, notes };
const [command, argument] = process.argv.slice(2);
if (!commands[command] || !argument) {
    console.error('Usage: node scripts/release.mjs prepare <version> | check <tag> | notes <tag>');
    process.exit(1);
}
try {
    commands[command](argument);
} catch (error) {
    console.error(/** @type {Error} */ (error).message);
    process.exit(1);
}
